-- =============================================================================
-- Northbank agent evals quickstart | 05 Evaluation dataset
-- 40 questions across 7 tiers. Each row has:
--   ground_truth_output       expected answer, computed in SQL against the source tables
--   ground_truth_invocations  tools the agent should call ([] = calling any tool is wrong)
-- The expected answers are only valid for the data generated by 01_synthetic_data.sql.
-- =============================================================================
USE DATABASE NORTHBANK_AGENT_EVALS;
USE SCHEMA NORTHBANK_AGENT_EVALS.DEMO;   -- datasets are created in the session schema
USE WAREHOUSE NORTHBANK_EVAL_WH;

CREATE OR REPLACE TABLE EVAL_QUESTIONS AS
SELECT $1:QUESTION_ID::VARCHAR  AS QUESTION_ID,
       $1:TIER::VARCHAR         AS TIER,
       $1:TRACK::VARCHAR        AS TRACK,
       $1:INPUT_QUERY::VARCHAR  AS INPUT_QUERY,
       $1:GROUND_TRUTH::VARIANT AS GROUND_TRUTH
FROM @EVAL_DATA_STAGE/eval_questions.ndjson (FILE_FORMAT => 'NORTHBANK_AGENT_EVALS.DEMO.JSON_FF');

SELECT TIER, COUNT(*) AS QUESTIONS,
       COUNT_IF(ARRAY_SIZE(GROUND_TRUTH:ground_truth_invocations) = 0) AS EXPECT_NO_TOOL
FROM EVAL_QUESTIONS GROUP BY 1 ORDER BY 1;   -- expect 40 questions in total

-- One row in full: what a good ground-truth row looks like
SELECT INPUT_QUERY, GROUND_TRUTH FROM EVAL_QUESTIONS WHERE QUESTION_ID = 'Q01';

-- A 5-question probe set for cheap first runs and judge experiments
CREATE OR REPLACE TABLE EVAL_QUESTIONS_PROBE AS
SELECT * FROM EVAL_QUESTIONS WHERE QUESTION_ID IN ('Q02', 'Q13', 'Q18', 'Q23', 'Q36');

-- Register both tables as evaluation datasets. Dataset names must be new: to reload
-- changed questions, register them under a new name (for example NORTHBANK_EVAL_V2)
-- and point the YAML configs at it, so earlier runs stay comparable.
CALL SYSTEM$CREATE_EVALUATION_DATASET(
  'Cortex Agent',
  'NORTHBANK_AGENT_EVALS.DEMO.EVAL_QUESTIONS',
  'NORTHBANK_AGENT_EVALS.DEMO.NORTHBANK_EVAL',
  OBJECT_CONSTRUCT('query_text', 'INPUT_QUERY', 'expected_tools', 'GROUND_TRUTH'));

CALL SYSTEM$CREATE_EVALUATION_DATASET(
  'Cortex Agent',
  'NORTHBANK_AGENT_EVALS.DEMO.EVAL_QUESTIONS_PROBE',
  'NORTHBANK_AGENT_EVALS.DEMO.NORTHBANK_EVAL_PROBE',
  OBJECT_CONSTRUCT('query_text', 'INPUT_QUERY', 'expected_tools', 'GROUND_TRUTH'));

SHOW DATASETS IN SCHEMA NORTHBANK_AGENT_EVALS.DEMO;
