  ARRAY_CONSTRUCT('J. Patel','S. Okafor','M. Evans','R. Campbell','A. Novak','L. Hughes','K. Ahmed','D. Murphy')[ABS(HASH(s.CUSTOMER_ID, s.NOTE_DATE,'ag')) % 8]::VARCHAR AS COLLEAGUE,
