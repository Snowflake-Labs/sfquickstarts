  ON a.MASTER_ID < b.MASTER_ID AND a.DOB = b.DOB AND a.ZIP = b.ZIP AND JAROWINKLER_SIMILARITY(UPPER(a.FIRST_NAME), UPPER(b.FIRST_NAME)) >= 90;

