--Keystone Identity Resolution & Eligibility - Lab Script
--Builds the KEYSTONE_DEMO database used by the Keystone caseworker console (frontend/ + backend/).
--All data is SYNTHETIC. Run top to bottom in a Snowsight SQL worksheet (Run All), about 5 minutes on MEDIUM.
--WARNING: CREATE OR REPLACE DATABASE - re-running regenerates all data.

--Step 1.1 - Create the warehouse, database, and schemas
USE ROLE SYSADMIN;
CREATE WAREHOUSE IF NOT EXISTS COMPUTE_WH WAREHOUSE_SIZE = 'MEDIUM' AUTO_SUSPEND = 60 AUTO_RESUME = TRUE;
USE WAREHOUSE COMPUTE_WH;

CREATE OR REPLACE DATABASE KEYSTONE_DEMO COMMENT = 'SYNTHETIC DEMO DATA - Keystone Benefits Administration (fictitious state human services agency)';
CREATE OR REPLACE SCHEMA KEYSTONE_DEMO.RAW COMMENT = 'SYNTHETIC DEMO - source system extracts, each with its own ID scheme and formats';
CREATE OR REPLACE SCHEMA KEYSTONE_DEMO.CORE COMMENT = 'SYNTHETIC DEMO - entity resolution output, unified constituent records';
CREATE OR REPLACE SCHEMA KEYSTONE_DEMO.MART COMMENT = 'SYNTHETIC DEMO - business views for demo walkthrough';
CREATE OR REPLACE SCHEMA KEYSTONE_DEMO.GOVERNANCE COMMENT = 'SYNTHETIC DEMO - masking policies, tags, secure views for sharing';

--Step 1.2 - Generate the 500K-person synthetic population (ground truth, not a source system)
CREATE OR REPLACE TABLE KEYSTONE_DEMO.RAW.SEED_PEOPLE COMMENT = 'SYNTHETIC DEMO - 500K ground truth population' AS
WITH g AS (SELECT ROW_NUMBER() OVER (ORDER BY TRUE) AS SEQ FROM TABLE(GENERATOR(ROWCOUNT => 500000))),
names AS (
  SELECT
    ['JAMES','MARY','ROBERT','PATRICIA','JOHN','JENNIFER','MICHAEL','LINDA','DAVID','ELIZABETH','WILLIAM','BARBARA','RICHARD','SUSAN','JOSEPH','JESSICA','THOMAS','SARAH','CHARLES','KAREN','CHRISTOPHER','NANCY','DANIEL','LISA','MATTHEW','BETTY','ANTHONY','MARGARET','MARK','SANDRA','DONALD','ASHLEY','STEVEN','KIMBERLY','PAUL','EMILY','ANDREW','DONNA','JOSHUA','MICHELLE']::ARRAY fn,
    ['SMITH','JOHNSON','WILLIAMS','BROWN','JONES','GARCIA','MILLER','DAVIS','RODRIGUEZ','MARTINEZ','HERNANDEZ','LOPEZ','GONZALEZ','WILSON','ANDERSON','THOMAS','TAYLOR','MOORE','JACKSON','MARTIN','LEE','PEREZ','THOMPSON','WHITE','HARRIS','SANCHEZ','CLARK','RAMIREZ','LEWIS','ROBINSON','WALKER','YOUNG','ALLEN','KING','WRIGHT','SCOTT','TORRES','NGUYEN','HILL','FLORES']::ARRAY ln,
    ['MAPLE','OAK','CEDAR','ELM','PINE','WALNUT','CHESTNUT','SPRUCE','WILLOW','BIRCH','POPLAR','HAWTHORNE','SYCAMORE','ASPEN','JUNIPER','BEECH','CHERRY','DOGWOOD','HICKORY','MAGNOLIA']::ARRAY streets,
    ['SPRINGFIELD','RIVERTON','FAIRVIEW','BRIDGEPORT','GREENFIELD','MIDDLETOWN','NEWCASTLE','CLEARWATER','HIGHLANDS','LAKEVIEW','OAKBROOK','SUMMIT']::ARRAY cities
)
SELECT
  g.SEQ AS PERSON_NO,
  GET(fn, UNIFORM(0, 39, RANDOM()))::VARCHAR AS FIRST_NAME,
  GET(ln, UNIFORM(0, 39, RANDOM()))::VARCHAR AS LAST_NAME,
  GET(ln, MOD(UNIFORM(0, 39, RANDOM()) + 7, 40))::VARCHAR AS ALT_LAST_NAME,
  DECODE(UNIFORM(0, 1, RANDOM()), 0, 'F', 'M') AS GENDER,
  DATEADD(day, -UNIFORM(6570, 25550, RANDOM()), '2026-01-01'::DATE) AS DOB,
  '9' || LPAD(TO_CHAR(MOD(g.SEQ * 81237491, 16777216)), 8, '0') AS SSN,
  UNIFORM(10, 9800, RANDOM())::VARCHAR || ' ' || GET(streets, UNIFORM(0, 19, RANDOM()))::VARCHAR || ' ' || DECODE(UNIFORM(0, 3, RANDOM()), 0, 'ST', 1, 'AVE', 2, 'RD', 3, 'DR') AS STREET_ADDRESS,
  GET(cities, UNIFORM(0, 11, RANDOM()))::VARCHAR AS CITY,
  'KY' AS STATE,
  LPAD(UNIFORM(10000, 99999, RANDOM()), 5, '0') AS ZIP,
  ROUND(LEAST(GREATEST(ABS(NORMAL(3800, 2800, RANDOM())), 500), 26000), 2) AS MONTHLY_INCOME,
  LEAST(UNIFORM(1, 7, RANDOM()), 6) AS HOUSEHOLD_SIZE
FROM g, names;

--Step 1.3 - Create the five source system extracts, each with its own IDs, formats, and data errors
CREATE OR REPLACE TABLE KEYSTONE_DEMO.RAW.SNAP_FOOD_ASSISTANCE COMMENT = 'SYNTHETIC DEMO - SNAP food assistance (source 1/4)' AS
WITH base AS (
  SELECT p.*, 0 AS REC_TYPE FROM KEYSTONE_DEMO.RAW.SEED_PEOPLE p WHERE p.PERSON_NO <= 150000
  UNION ALL
  SELECT p.*, 1 AS REC_TYPE FROM KEYSTONE_DEMO.RAW.SEED_PEOPLE p WHERE p.PERSON_NO <= 3000   -- planted duplicate SNAP cases
),
d AS (
  SELECT b.*,
    CASE WHEN MOD(b.PERSON_NO + b.REC_TYPE, 3) = 0 THEN SUBSTR(b.LAST_NAME, 1, 1) || SUBSTR(b.LAST_NAME, 3) ELSE b.LAST_NAME END AS LAST_NAME_D,
    CASE WHEN MOD(b.PERSON_NO + b.REC_TYPE, 7) = 0 THEN b.ALT_LAST_NAME ELSE b.LAST_NAME END AS LAST_NAME_M,
    CASE WHEN MOD(b.PERSON_NO + b.REC_TYPE, 11) = 0 THEN SUBSTR(b.SSN, 1, 10) || CASE WHEN RIGHT(b.SSN, 1) = '7' THEN '8' ELSE '7' END ELSE b.SSN END AS SSN_D,
    CASE WHEN MOD(b.PERSON_NO + b.REC_TYPE, 13) = 0 THEN DATEADD(day, 1, b.DOB) ELSE b.DOB END AS DOB_D,
    REPLACE(REPLACE(b.STREET_ADDRESS, ' ST', ' STREET'), ' AVE', ' AVENUE') AS ADDR_D
  FROM base b
)
SELECT
  CASE WHEN REC_TYPE = 1 THEN 'SNP-D' || LPAD(PERSON_NO, 6, '0') ELSE 'SNP-' || LPAD(PERSON_NO, 6, '0') END AS SNAP_CASE_ID,
  CASE WHEN REC_TYPE = 1 THEN LAST_NAME_M || ', ' || FIRST_NAME WHEN MOD(PERSON_NO, 7) = 0 THEN ALT_LAST_NAME || ', ' || FIRST_NAME ELSE LAST_NAME_D || ', ' || FIRST_NAME END AS CASEHOLDER_NAME,
  DOB_D AS DATE_OF_BIRTH, SSN_D AS SSN,
  ADDR_D || ', ' || CITY || ', ' || STATE || ' ' || ZIP AS FULL_ADDRESS,
  MONTHLY_INCOME, HOUSEHOLD_SIZE, 'ACTIVE' AS CASE_STATUS,
  DATEADD(day, -UNIFORM(30, 900, RANDOM()), CURRENT_DATE()) AS ENROLLMENT_DATE
FROM d;

