--Step 3.3 - Live intake pipeline: raw table + incremental Dynamic Tables
CREATE OR REPLACE TABLE KEYSTONE_DEMO.RAW.LIVE_INTAKE (
  EVENT_ID VARCHAR, SOURCE_SYSTEM VARCHAR, SOURCE_RECORD_ID VARCHAR, MASTER_ID VARCHAR,
  CITY VARCHAR, ELIGIBILITY_RESULT VARCHAR, RECEIVED_AT TIMESTAMP_NTZ
) COMMENT = 'SYNTHETIC DEMO - isolated append-only live intake events';

CREATE OR REPLACE DYNAMIC TABLE KEYSTONE_DEMO.CORE.LIVE_INTAKE_RESOLVED
  TARGET_LAG = DOWNSTREAM WAREHOUSE = COMPUTE_WH REFRESH_MODE = INCREMENTAL INITIALIZE = ON_CREATE
  COMMENT = 'SYNTHETIC DEMO - incremental intake-to-master join'
AS SELECT i.EVENT_ID, i.SOURCE_SYSTEM, i.SOURCE_RECORD_ID, i.MASTER_ID, i.CITY, i.ELIGIBILITY_RESULT, i.RECEIVED_AT,
     c.SOURCE_RECORD_COUNT AS MATCHED_SOURCE_RECORD_COUNT
   FROM KEYSTONE_DEMO.RAW.LIVE_INTAKE i
   LEFT JOIN KEYSTONE_DEMO.CORE.CONSTITUENT_MASTER c ON i.MASTER_ID = c.MASTER_ID;

CREATE OR REPLACE DYNAMIC TABLE KEYSTONE_DEMO.MART.LIVE_INTAKE_ELIGIBILITY
  TARGET_LAG = '1 minute' WAREHOUSE = COMPUTE_WH REFRESH_MODE = INCREMENTAL INITIALIZE = ON_CREATE
  COMMENT = 'SYNTHETIC DEMO - eligibility recomputed from resolved intake and governed constituent data'
AS SELECT r.EVENT_ID, r.SOURCE_RECORD_ID, r.MASTER_ID, r.SOURCE_SYSTEM, r.CITY, r.RECEIVED_AT,
     c.MONTHLY_INCOME, c.HOUSEHOLD_SIZE,
     (1579 + 550 * (COALESCE(c.HOUSEHOLD_SIZE, 1) - 1)) AS GROSS_MONTHLY_LIMIT,
     CASE WHEN c.MASTER_ID IS NULL OR c.MONTHLY_INCOME IS NULL THEN 'MANUAL_REVIEW'
          WHEN c.MONTHLY_INCOME <= 1579 + 550 * (COALESCE(c.HOUSEHOLD_SIZE, 1) - 1) THEN 'PASS' ELSE 'FAIL' END AS ELIGIBILITY_RESULT
   FROM KEYSTONE_DEMO.CORE.LIVE_INTAKE_RESOLVED r
   LEFT JOIN KEYSTONE_DEMO.CORE.CONSTITUENT_MASTER c ON r.MASTER_ID = c.MASTER_ID;

CREATE OR REPLACE DYNAMIC TABLE KEYSTONE_DEMO.MART.LIVE_INTAKE_METRICS
  TARGET_LAG = '5 minutes' WAREHOUSE = COMPUTE_WH REFRESH_MODE = INCREMENTAL INITIALIZE = ON_CREATE
  COMMENT = 'SYNTHETIC DEMO - live intake totals by source and eligibility'
AS SELECT SOURCE_SYSTEM, CITY, ELIGIBILITY_RESULT, COUNT(*) AS EVENT_COUNT, MAX(RECEIVED_AT) AS LATEST_EVENT_AT
   FROM KEYSTONE_DEMO.CORE.LIVE_INTAKE_RESOLVED GROUP BY SOURCE_SYSTEM, CITY, ELIGIBILITY_RESULT;

--Step 3.4 - Dashboard views used by the console
CREATE OR REPLACE VIEW KEYSTONE_DEMO.MART.V_LIVE_PIPELINE_STATUS AS
