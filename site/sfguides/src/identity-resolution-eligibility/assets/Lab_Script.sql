--Step 2.1 - Standardize all source records into one shape
CREATE OR REPLACE TABLE KEYSTONE_DEMO.CORE.STG_PERSON_RECORDS COMMENT = 'SYNTHETIC DEMO - normalized union of all source records' AS
SELECT 'SNAP_FOOD_ASSISTANCE' AS SOURCE_SYSTEM, SNAP_CASE_ID AS SYSTEM_ID,
  TRIM(SUBSTR(CASEHOLDER_NAME, POSITION(', ' IN CASEHOLDER_NAME) + 2)) AS FIRST_NAME,
  TRIM(SUBSTR(CASEHOLDER_NAME, 1, POSITION(',' IN CASEHOLDER_NAME) - 1)) AS LAST_NAME,
  DATE_OF_BIRTH AS DOB, REPLACE(SSN, '-', '') AS NORM_SSN,
  TRIM(SPLIT_PART(FULL_ADDRESS, ',', 2)) AS CITY, RIGHT(FULL_ADDRESS, 5) AS ZIP, MONTHLY_INCOME, HOUSEHOLD_SIZE
FROM KEYSTONE_DEMO.RAW.SNAP_FOOD_ASSISTANCE
UNION ALL
SELECT 'MEDICAID', MEDICAID_MEMBER_ID,
  TRIM(SUBSTR(MEMBER_NAME, POSITION(', ' IN MEMBER_NAME) + 2)), TRIM(SUBSTR(MEMBER_NAME, 1, POSITION(',' IN MEMBER_NAME) - 1)),
  DATE_OF_BIRTH, REPLACE(SSN, '-', ''), RESIDENCE_CITY, RESIDENCE_ZIP, NULL, NULL
FROM KEYSTONE_DEMO.RAW.MEDICAID_ENROLLMENT
UNION ALL
SELECT 'CHILDCARE_SUBSIDY', PROVIDER_CASE_ID,
  SPLIT_PART(PARENT_NAME, ' ', 1), SPLIT_PART(PARENT_NAME, ' ', 2),
  PARENT_DOB, REPLACE(PARENT_SSN, '-', ''), CITY, ZIP, NULL, CHILD_COUNT + 1
FROM KEYSTONE_DEMO.RAW.CHILDCARE_SUBSIDY
UNION ALL
SELECT 'WORKFORCE_TRAINING', PARTICIPANT_ID,
  SPLIT_PART(PARTICIPANT_NAME, ' ', 1), SPLIT_PART(PARTICIPANT_NAME, ' ', 2),
  DATE_OF_BIRTH, REPLACE(SSN, '-', ''), CITY, ZIP, NULL, NULL
FROM KEYSTONE_DEMO.RAW.WORKFORCE_TRAINING
UNION ALL
SELECT 'STATE_TAX_RECORDS', TAX_ACCOUNT_ID,
  TRIM(SUBSTR(FILER_NAME, POSITION(', ' IN FILER_NAME) + 2)), TRIM(SUBSTR(FILER_NAME, 1, POSITION(',' IN FILER_NAME) - 1)),
  FILER_DOB, REPLACE(SSN, '-', ''), CITY, ZIP, ROUND(ANNUAL_INCOME / 12, 2), DEPENDENTS + 1
FROM KEYSTONE_DEMO.RAW.STATE_TAX_RECORDS;

--Step 2.2 - Deterministic match: cluster records on exact SSN
CREATE OR REPLACE TABLE KEYSTONE_DEMO.CORE.ER_DETERMINISTIC_CLUSTERS AS
SELECT DENSE_RANK() OVER (ORDER BY NORM_SSN) AS DET_CLUSTER_NO,
  COUNT(*) OVER (PARTITION BY NORM_SSN) AS CLUSTER_SIZE, stg.*
FROM KEYSTONE_DEMO.CORE.STG_PERSON_RECORDS stg;

--Step 2.3 - Probabilistic match: Jaro-Winkler names, blocked on ZIP and DOB +/- 1 day
CREATE OR REPLACE TABLE KEYSTONE_DEMO.CORE.ER_PROBABILISTIC_LINKS AS
WITH singles AS (SELECT * FROM KEYSTONE_DEMO.CORE.ER_DETERMINISTIC_CLUSTERS WHERE CLUSTER_SIZE = 1),
anchors AS (SELECT * FROM KEYSTONE_DEMO.CORE.ER_DETERMINISTIC_CLUSTERS WHERE CLUSTER_SIZE > 1),
cand AS (
  SELECT s.DET_CLUSTER_NO AS S_C, a.DET_CLUSTER_NO AS A_C,
    JAROWINKLER_SIMILARITY(UPPER(s.FIRST_NAME)||' '||UPPER(s.LAST_NAME), UPPER(a.FIRST_NAME)||' '||UPPER(a.LAST_NAME)) AS FULL_SCORE,
    JAROWINKLER_SIMILARITY(UPPER(s.FIRST_NAME), UPPER(a.FIRST_NAME)) AS FIRST_SCORE
  FROM singles s JOIN anchors a ON a.ZIP = s.ZIP
  WHERE (a.DOB=s.DOB OR a.DOB=DATEADD(day,1,s.DOB) OR a.DOB=DATEADD(day,-1,s.DOB))
    AND (JAROWINKLER_SIMILARITY(UPPER(s.FIRST_NAME)||' '||UPPER(s.LAST_NAME), UPPER(a.FIRST_NAME)||' '||UPPER(a.LAST_NAME)) >= 85
      OR JAROWINKLER_SIMILARITY(UPPER(s.FIRST_NAME), UPPER(a.FIRST_NAME)) >= 90)
),
pass1 AS (
  SELECT S_C, A_C, GREATEST(FULL_SCORE, FIRST_SCORE) AS SCORE FROM cand
  QUALIFY ROW_NUMBER() OVER (PARTITION BY S_C ORDER BY SCORE DESC, A_C) = 1
),
pass2 AS (
  SELECT s.DET_CLUSTER_NO AS S_C, a.DET_CLUSTER_NO AS A_C,
    JAROWINKLER_SIMILARITY(UPPER(s.FIRST_NAME)||' '||UPPER(s.LAST_NAME), UPPER(a.FIRST_NAME)||' '||UPPER(a.LAST_NAME)) AS SCORE
  FROM singles s JOIN singles a ON s.DET_CLUSTER_NO < a.DET_CLUSTER_NO AND a.ZIP=s.ZIP
    AND (a.DOB=s.DOB OR a.DOB=DATEADD(day,1,s.DOB) OR a.DOB=DATEADD(day,-1,s.DOB))
    AND JAROWINKLER_SIMILARITY(UPPER(s.FIRST_NAME)||' '||UPPER(s.LAST_NAME), UPPER(a.FIRST_NAME)||' '||UPPER(a.LAST_NAME)) >= 85
  WHERE s.DET_CLUSTER_NO NOT IN (SELECT S_C FROM pass1) AND a.DET_CLUSTER_NO NOT IN (SELECT S_C FROM pass1)
  QUALIFY ROW_NUMBER() OVER (PARTITION BY s.DET_CLUSTER_NO ORDER BY SCORE DESC, a.DET_CLUSTER_NO) = 1
    AND ROW_NUMBER() OVER (PARTITION BY a.DET_CLUSTER_NO ORDER BY SCORE DESC, s.DET_CLUSTER_NO) = 1
)
SELECT S_C AS SINGLE_CLUSTER_NO, A_C AS TARGET_CLUSTER_NO, SCORE AS MATCH_SCORE FROM pass1
UNION ALL SELECT S_C, A_C, SCORE FROM pass2;

--Step 2.4 - Map every record to a master ID, then build one row per constituent
CREATE OR REPLACE TABLE KEYSTONE_DEMO.CORE.MATCH_LINK AS
SELECT 'KM-' || LPAD(c.FC, 6, '0') AS MASTER_ID,
  'R' || LPAD(ROW_NUMBER() OVER (ORDER BY c.FC, c.SOURCE_SYSTEM, c.SYSTEM_ID), 7, '0') AS RECORD_ID,
  c.SOURCE_SYSTEM, c.SYSTEM_ID, c.FIRST_NAME, c.LAST_NAME, c.DOB, c.NORM_SSN,
  c.CITY, c.ZIP, c.MONTHLY_INCOME, c.HOUSEHOLD_SIZE, c.MT AS MATCH_TYPE, c.MS AS MATCH_SCORE
FROM (
  SELECT d.*, COALESCE(p.TARGET_CLUSTER_NO, d.DET_CLUSTER_NO) AS FC,
    CASE WHEN p.TARGET_CLUSTER_NO IS NOT NULL THEN 'PROBABILISTIC' WHEN d.CLUSTER_SIZE > 1 THEN 'DETERMINISTIC' ELSE 'UNRESOLVED' END AS MT,
    CASE WHEN p.TARGET_CLUSTER_NO IS NOT NULL THEN p.MATCH_SCORE WHEN d.CLUSTER_SIZE > 1 THEN 100 ELSE 0 END AS MS
  FROM KEYSTONE_DEMO.CORE.ER_DETERMINISTIC_CLUSTERS d
  LEFT JOIN KEYSTONE_DEMO.CORE.ER_PROBABILISTIC_LINKS p ON p.SINGLE_CLUSTER_NO = d.DET_CLUSTER_NO
) c;

CREATE OR REPLACE TABLE KEYSTONE_DEMO.CORE.CONSTITUENT_MASTER AS
WITH canon AS (
  SELECT MASTER_ID, MODE(FIRST_NAME) AS FIRST_NAME, MODE(LAST_NAME) AS LAST_NAME,
    MODE(DOB) AS DOB, MODE(NORM_SSN) AS NORM_SSN, MODE(CITY) AS CITY, MODE(ZIP) AS ZIP
  FROM KEYSTONE_DEMO.CORE.MATCH_LINK GROUP BY MASTER_ID
)
SELECT c.MASTER_ID, c.FIRST_NAME, c.LAST_NAME, c.DOB, c.NORM_SSN, c.CITY, c.ZIP,
  MAX(m.MONTHLY_INCOME) AS MONTHLY_INCOME, MAX(m.HOUSEHOLD_SIZE) AS HOUSEHOLD_SIZE,
  COUNT(*) AS SOURCE_RECORD_COUNT, COUNT(DISTINCT m.SOURCE_SYSTEM) AS SYSTEMS_FOUND_IN,
  LISTAGG(DISTINCT m.SOURCE_SYSTEM, ' | ') AS SOURCE_SYSTEMS,
  SUM(IFF(m.MATCH_TYPE = 'DETERMINISTIC', 1, 0)) AS DETERMINISTIC_MATCHES,
  SUM(IFF(m.MATCH_TYPE = 'PROBABILISTIC', 1, 0)) AS PROBABILISTIC_MATCHES,
  MAX(m.MATCH_SCORE) AS BEST_MATCH_SCORE
FROM KEYSTONE_DEMO.CORE.MATCH_LINK m JOIN canon c ON c.MASTER_ID = m.MASTER_ID
GROUP BY c.MASTER_ID, c.FIRST_NAME, c.LAST_NAME, c.DOB, c.NORM_SSN, c.CITY, c.ZIP;

--Step 3.1 - SNAP eligibility (example rule: $1,579 + $550 per extra household member)
-- Demo rule (not an official threshold): $1,579 + $550 per extra household member.
CREATE OR REPLACE VIEW KEYSTONE_DEMO.MART.V_SNAP_ELIGIBILITY AS
SELECT cm.MASTER_ID, cm.FIRST_NAME, cm.LAST_NAME, cm.CITY, cm.ZIP,
  cm.MONTHLY_INCOME, cm.HOUSEHOLD_SIZE,
  ROUND(1579 + 550 * (COALESCE(cm.HOUSEHOLD_SIZE, 1) - 1), 2) AS GROSS_MONTHLY_LIMIT,
  CASE WHEN cm.MONTHLY_INCOME IS NULL THEN 'MANUAL_REVIEW'
    WHEN cm.MONTHLY_INCOME <= 1579 + 550 * (COALESCE(cm.HOUSEHOLD_SIZE, 1) - 1) THEN 'PASS' ELSE 'FAIL' END AS ELIGIBILITY_RESULT,
  CASE WHEN cm.MONTHLY_INCOME IS NULL THEN 'INCOME_UNVERIFIED - MANUAL REVIEW'
    WHEN cm.MONTHLY_INCOME <= 1579 + 550 * (COALESCE(cm.HOUSEHOLD_SIZE, 1) - 1) THEN 'ELIGIBLE - INCOME WITHIN LIMIT'
    ELSE 'INELIGIBLE - INCOME EXCEEDS LIMIT' END AS DETERMINATION_REASON,
  CONTAINS(cm.SOURCE_SYSTEMS, 'SNAP_FOOD_ASSISTANCE') AS CURRENTLY_ENROLLED_SNAP
FROM KEYSTONE_DEMO.CORE.CONSTITUENT_MASTER cm;

--Step 3.2 - Caseworker views: enrollment, outreach, duplicates, match review, case context
CREATE OR REPLACE VIEW KEYSTONE_DEMO.MART.V_CROSS_PROGRAM_ENROLLMENT AS
SELECT cm.MASTER_ID, cm.FIRST_NAME, cm.LAST_NAME, cm.DOB, cm.CITY, cm.ZIP,
  CONTAINS(cm.SOURCE_SYSTEMS, 'SNAP_FOOD_ASSISTANCE') AS ENROLLED_SNAP,
  CONTAINS(cm.SOURCE_SYSTEMS, 'MEDICAID') AS ENROLLED_MEDICAID,
  CONTAINS(cm.SOURCE_SYSTEMS, 'CHILDCARE_SUBSIDY') AS ENROLLED_CHILDCARE,
  CONTAINS(cm.SOURCE_SYSTEMS, 'WORKFORCE_TRAINING') AS ENROLLED_WORKFORCE,
  cm.SYSTEMS_FOUND_IN - IFF(CONTAINS(cm.SOURCE_SYSTEMS, 'STATE_TAX_RECORDS'), 1, 0) AS PROGRAM_ENROLLMENT_COUNT,
  cm.SOURCE_SYSTEMS
FROM KEYSTONE_DEMO.CORE.CONSTITUENT_MASTER cm;

CREATE OR REPLACE VIEW KEYSTONE_DEMO.MART.V_ELIGIBLE_NOT_ENROLLED AS
SELECT MASTER_ID, FIRST_NAME, LAST_NAME, CITY, ZIP, MONTHLY_INCOME, HOUSEHOLD_SIZE, GROSS_MONTHLY_LIMIT
FROM KEYSTONE_DEMO.MART.V_SNAP_ELIGIBILITY WHERE ELIGIBILITY_RESULT = 'PASS' AND NOT CURRENTLY_ENROLLED_SNAP;

CREATE OR REPLACE VIEW KEYSTONE_DEMO.MART.V_DUPLICATE_ENROLLMENT AS
SELECT m.MASTER_ID, m.SOURCE_SYSTEM AS AFFECTED_PROGRAM, COUNT(*) AS ENROLLMENT_RECORDS,
  LISTAGG(m.SYSTEM_ID, ', ') AS SYSTEM_RECORD_IDS, MIN(m.FIRST_NAME || ' ' || m.LAST_NAME) AS RECORD_NAME, MAX(m.DOB) AS DOB
FROM KEYSTONE_DEMO.CORE.MATCH_LINK m WHERE m.SOURCE_SYSTEM <> 'STATE_TAX_RECORDS'
GROUP BY m.MASTER_ID, m.SOURCE_SYSTEM HAVING COUNT(*) > 1;

CREATE OR REPLACE VIEW KEYSTONE_DEMO.MART.V_MATCH_REVIEW_QUEUE AS
SELECT a.MASTER_ID, a.FIRST_NAME, a.LAST_NAME, a.DOB, a.ZIP,
  b.MASTER_ID AS SUGGESTED_MATCH_MASTER_ID, b.FIRST_NAME AS SUGGESTED_FIRST_NAME, b.LAST_NAME AS SUGGESTED_LAST_NAME,
  JAROWINKLER_SIMILARITY(UPPER(a.FIRST_NAME) || ' ' || UPPER(a.LAST_NAME), UPPER(b.FIRST_NAME) || ' ' || UPPER(b.LAST_NAME)) AS SUGGESTED_MATCH_SCORE
FROM (SELECT MASTER_ID, FIRST_NAME, LAST_NAME, DOB, ZIP FROM KEYSTONE_DEMO.CORE.CONSTITUENT_MASTER WHERE SYSTEMS_FOUND_IN = 1 AND DETERMINISTIC_MATCHES = 0 AND PROBABILISTIC_MATCHES = 0) a
