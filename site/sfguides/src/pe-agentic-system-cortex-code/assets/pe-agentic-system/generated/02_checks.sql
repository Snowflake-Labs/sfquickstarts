USE DATABASE <your db>;
USE SCHEMA <your db>.<your schema>;
USE WAREHOUSE <your warehouse>;
SELECT * FROM <your db>.<your schema>.WATERFALL_RECONCILIATION
ORDER BY CASE_ID;

SELECT <your db>.<your schema>.RECONCILIATION_FAILURE_COUNT(
  SELECT PROCEEDS, ALLOCATED_TOTAL, TOLERANCE
  FROM <your db>.<your schema>.WATERFALL_RECONCILIATION
) AS VALUE;

SELECT SNOWFLAKE.CORE.NULL_COUNT(
  SELECT AMOUNT FROM <your db>.<your schema>.WATERFALL_ALLOCATIONS
) AS NULL_AMOUNT_COUNT;

SELECT SNOWFLAKE.CORE.DUPLICATE_COUNT(
  SELECT CASE_ID FROM <your db>.<your schema>.WATERFALL_CASES
) AS DUPLICATE_CASE_COUNT;

SELECT COUNT(*) AS INCOMPLETE_CASE_COUNT
FROM <your db>.<your schema>.WATERFALL_RECONCILIATION
WHERE NOT COMPLETE;

SELECT COUNT(*) AS ORPHAN_ALLOCATION_COUNT
FROM <your db>.<your schema>.WATERFALL_ALLOCATIONS allocations
WHERE NOT EXISTS (
  SELECT 1 FROM <your db>.<your schema>.WATERFALL_CASES cases
  WHERE cases.CASE_ID = allocations.CASE_ID
);

SELECT COUNT(*) - COUNT(DISTINCT CASE_ID, ALLOCATION_ID) AS DUPLICATE_ALLOCATION_COUNT
FROM <your db>.<your schema>.WATERFALL_ALLOCATIONS;

SELECT COUNT(*) AS NEGATIVE_ALLOCATION_COUNT
FROM <your db>.<your schema>.WATERFALL_ALLOCATIONS
WHERE AMOUNT < 0;

SELECT <your db>.<your schema>.REVIEW_RECONCILIATION('SHORTFALL') AS REVIEW;

SELECT <your db>.<your schema>.REVIEW_RECONCILIATION('UNKNOWN') AS REVIEW;